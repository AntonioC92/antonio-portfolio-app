/**
 * Vite SSR prerender — no Puppeteer required.
 * Runs on Cloudflare Pages build environment (Node.js only).
 *
 * Flow:
 *  1. vite build (client bundle → dist/)            ← done by caller
 *  2. vite build --ssr entry-server.tsx             ← this script does it
 *  3. For each route: render to string, inject into dist/index.html template
 *  4. Write sitemap.xml, rss.xml and feeds/linkedin.json
 */

import { build } from 'vite';
import { access, mkdir, readFile, readdir, writeFile, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const rootDir       = path.resolve(__dirname, '..');
const distDir       = path.resolve(rootDir, 'dist');
const serverDistDir = path.resolve(rootDir, 'dist-server');
const resourcesDir  = path.resolve(rootDir, 'src/content/resources');
const linkedinDir   = path.resolve(rootDir, 'src/content/linkedin');
const siteUrl       = 'https://carusomartech.com';

const STATIC_ROUTES = [
  '/',
  '/work',
  '/services',
  '/about',
  '/insights',
  '/contact',
  '/privacy-policy',
];

// ─── helpers ────────────────────────────────────────────────────────────────

function parseFrontmatter(raw) {
  if (!raw.startsWith('---')) return {};
  const end = raw.indexOf('\n---', 3);
  if (end === -1) return {};
  const header = raw.slice(3, end).trim();
  const fm = {};
  header.split('\n').forEach((line) => {
    const sep = line.indexOf(':');
    if (sep === -1) return;
    const key   = line.slice(0, sep).trim();
    const value = line.slice(sep + 1).trim().replace(/^["'](.*)["']$/, '$1');
    fm[key] = value;
  });
  return fm;
}

async function getResources() {
  let files;
  try {
    files = await readdir(resourcesDir);
  } catch {
    return [];
  }
  const resources = [];
  for (const file of files.filter((f) => f.endsWith('.md'))) {
    const raw = await readFile(path.join(resourcesDir, file), 'utf8');
    const fm  = parseFrontmatter(raw);
    if (!fm.slug) continue;
    resources.push({
      slug:            fm.slug,
      title:           fm.title ?? fm.slug,
      metaDescription: fm.metaDescription ?? fm.description ?? '',
      category:        fm.category ?? '',
      date:            fm.date ?? '',
      lastUpdated:     fm.lastUpdated ?? fm.date ?? '',
    });
  }
  return resources.sort(
    (a, b) => new Date(b.date).getTime() - new Date(a.date).getTime()
  );
}

function outputPathForRoute(route) {
  if (route === '/') return path.join(distDir, 'index.html');
  const clean = route.replace(/^\/+|\/+$/g, '');
  return path.join(distDir, clean, 'index.html');
}

function buildSitemap(resources) {
  // All loc values carry a trailing slash. Cloudflare Pages serves this
  // static build as one index.html per directory and 308-redirects any
  // non-trailing-slash request to the trailing-slash form (confirmed via
  // curl on live routes, 2026-08-10) — so a sitemap without trailing
  // slashes submits URLs that immediately redirect, which is exactly what
  // GSC's "Redirect error" / failed-validation findings were flagging.
  // Every canonical/ogUrl in the page components was fixed to match.
  const staticUrls = [
    { loc: `${siteUrl}/`,                      changefreq: 'weekly',  priority: '1.0' },
    { loc: `${siteUrl}/work/`,                 changefreq: 'monthly', priority: '0.9' },
    { loc: `${siteUrl}/services/`,             changefreq: 'monthly', priority: '0.9' },
    { loc: `${siteUrl}/about/`,                changefreq: 'monthly', priority: '0.8' },
    { loc: `${siteUrl}/insights/`,             changefreq: 'weekly',  priority: '0.8' },
    { loc: `${siteUrl}/contact/`,              changefreq: 'yearly',  priority: '0.5' },
    { loc: `${siteUrl}/privacy-policy/`,       changefreq: 'yearly',  priority: '0.3' },
  ];
  const resourceUrls = resources.map((r) => ({
    loc:        `${siteUrl}/insights/${r.slug}/`,
    lastmod:    r.lastUpdated,
    changefreq: 'monthly',
    priority:   '0.7',
  }));
  const entries = [...staticUrls, ...resourceUrls].map((u) => {
    const parts = ['  <url>', `    <loc>${u.loc}</loc>`];
    if (u.lastmod) parts.push(`    <lastmod>${u.lastmod}</lastmod>`);
    parts.push(`    <changefreq>${u.changefreq}</changefreq>`);
    parts.push(`    <priority>${u.priority}</priority>`);
    parts.push('  </url>');
    return parts.join('\n');
  });
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${entries.join('\n')}\n</urlset>\n`;
}

const escapeXml = (value) =>
  value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');

const fileExists = (file) => access(file).then(() => true, () => false);

// Share image generated by `npm run og` (public/og/<slug>.jpg, copied into dist/).
async function shareImageFor(slug) {
  return (await fileExists(path.join(distDir, 'og', `${slug}.jpg`)))
    ? `${siteUrl}/og/${slug}.jpg`
    : `${siteUrl}/preview.png`;
}

function buildRss(resources, images) {
  const items = resources.map((r) => {
    const url = `${siteUrl}/insights/${r.slug}/`;
    return [
      '    <item>',
      `      <title>${escapeXml(r.title)}</title>`,
      `      <link>${url}</link>`,
      `      <guid isPermaLink="true">${url}</guid>`,
      `      <pubDate>${new Date(`${r.date}T09:00:00Z`).toUTCString()}</pubDate>`,
      `      <description>${escapeXml(r.metaDescription)}</description>`,
      r.category ? `      <category>${escapeXml(r.category)}</category>` : null,
      `      <enclosure url="${images[r.slug]}" type="${images[r.slug].endsWith('.png') ? 'image/png' : 'image/jpeg'}" length="0"/>`,
      '    </item>',
    ].filter(Boolean).join('\n');
  });
  return `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>Caruso Martech Insights</title>
    <link>${siteUrl}/insights/</link>
    <description>Practical writing on marketing systems, attribution, automation and AI search.</description>
    <language>en</language>
    <atom:link href="${siteUrl}/rss.xml" rel="self" type="application/rss+xml"/>
${items.join('\n')}
  </channel>
</rss>
`;
}

// Feed for the n8n LinkedIn workflow. Only articles with a hand-reviewed
// LinkedIn caption in src/content/linkedin/<slug>.md are included, so older
// posts never get auto-shared by accident.
async function buildLinkedInFeed(resources, images) {
  const items = [];
  for (const r of resources) {
    let text;
    try {
      text = (await readFile(path.join(linkedinDir, `${r.slug}.md`), 'utf8')).trim();
    } catch {
      continue;
    }
    items.push({
      slug:     r.slug,
      url:      `${siteUrl}/insights/${r.slug}/`,
      title:    r.title,
      summary:  r.metaDescription,
      category: r.category,
      date:     r.date,
      image:    images[r.slug],
      text,
    });
  }
  return `${JSON.stringify({ generated: new Date().toISOString(), items }, null, 2)}\n`;
}

// ─── main ───────────────────────────────────────────────────────────────────

async function run() {
  // 1. Build SSR bundle
  console.log('📦  Building SSR bundle…');
  await build({
    root: rootDir,
    build: {
      ssr:    path.resolve(rootDir, 'src/entry-server.tsx'),
      outDir: serverDistDir,
      // Use .mjs so Node.js 18 treats the output as ESM without needing
      // "type": "module" in package.json.
      rollupOptions: { output: { format: 'esm', entryFileNames: '[name].mjs' } },
    },
    logLevel: 'warn',
  });

  // 2. Load render function from SSR bundle
  const serverEntry = pathToFileURL(
    path.join(serverDistDir, 'entry-server.mjs')
  ).href;
  const { render } = await import(serverEntry);

  // 3. Load HTML template produced by client build, then:
  //    a) Inline the font-face CSS so the page has no render-blocking
  //       <link rel="stylesheet"> at all.  The CSS file only contains
  //       @font-face declarations (< 1 KB after the latin-only subset change
  //       in src/fonts.css) so inlining is safe and eliminates one full
  //       round-trip under slow connections.
  //    b) Extract the woff2 font URLs from the inlined CSS and inject
  //       <link rel="preload"> hints right after the GTM preconnect tag.
  //       This causes the browser to start fetching the font files as soon
  //       as the first few hundred bytes of HTML arrive — in parallel with
  //       the JS chunks — instead of waiting until the browser has parsed
  //       the entire head and discovered the urls inside the <style> tag.
  const rawTemplate = await readFile(path.join(distDir, 'index.html'), 'utf8');
  let template = rawTemplate;
  const cssLinkRe = /<link rel="stylesheet" crossorigin href="(\/assets\/[^"]+\.css)">/;
  const cssLinkMatch = rawTemplate.match(cssLinkRe);
  if (cssLinkMatch) {
    const cssHref = cssLinkMatch[1]; // e.g. "/assets/index-Cj5IOoc2.css"
    const cssFilePath = path.join(distDir, cssHref.replace(/^\//, ''));
    try {
      const cssContent = await readFile(cssFilePath, 'utf8');
      // Replace the blocking <link> with an inline <style> so the browser
      // never has to open a separate connection before it can paint.
      template = rawTemplate.replace(
        cssLinkMatch[0],
        `<style id="font-face">${cssContent}</style>`
      );
      console.log(`  ♻  Font CSS inlined (${cssContent.length} bytes, was render-blocking)`);

      // Extract woff2 URLs from the font CSS and inject preload hints early
      // in the head so the browser fetches fonts before it has even finished
      // parsing the 26 KB styled-components block.
      const fontUrlRe = /url\(['"]?(\/assets\/[^"')]+\.woff2)['"]?\)/g;
      const fontPreloadLinks = [];
      let fontMatch;
      while ((fontMatch = fontUrlRe.exec(cssContent)) !== null) {
        fontPreloadLinks.push(
          `<link rel="preload" as="font" type="font/woff2" crossorigin href="${fontMatch[1]}">`
        );
      }
      if (fontPreloadLinks.length > 0) {
        // Inject right after the GTM preconnect hint — the earliest stable
        // marker in the head that survives every build.
        const preconnectTag = `<link rel="preconnect" href="https://www.googletagmanager.com" />`;
        template = template.replace(
          preconnectTag,
          preconnectTag + '\n    ' + fontPreloadLinks.join('\n    ')
        );
        console.log(`  🔤  Font preloads injected: ${fontPreloadLinks.map(l => l.match(/href="([^"]+)"/)?.[1]?.split('/').pop()).join(', ')}`);
      }
    } catch (e) {
      console.warn(`  ⚠  Could not inline font CSS (${e.message}) — falling back to non-blocking load`);
      // Fallback: load the CSS non-blocking so it at least doesn't delay FCP.
      template = rawTemplate.replace(
        cssLinkMatch[0],
        `<link rel="preload" href="${cssHref}" as="style" onload="this.onload=null;this.rel='stylesheet'">` +
        `<noscript><link rel="stylesheet" crossorigin href="${cssHref}"></noscript>`
      );
    }
  }

  // 4. Collect routes
  const resources = await getResources();
  const routes = [
    ...STATIC_ROUTES,
    ...resources.map((r) => `/insights/${r.slug}`),
  ];

  const images = {};
  for (const r of resources) images[r.slug] = await shareImageFor(r.slug);

  // 5. Render each route
  let ok = 0;
  let failed = 0;
  for (const route of routes) {
    try {
      const { html, styleTags, headTags } = render(route);

      let page = template
        .replace('<!--app-html-->', html)
        .replace('<!--app-head-->', headTags ? `${headTags}\n    ${styleTags}` : styleTags);

      // Articles without a generated share image fall back to the site preview.
      const slug = route.startsWith('/insights/') ? route.slice('/insights/'.length) : null;
      if (slug && images[slug] && !images[slug].endsWith(`/og/${slug}.jpg`)) {
        page = page.replaceAll(`${siteUrl}/og/${slug}.jpg`, images[slug]);
        console.warn(`  ⚠  ${route}: no og/${slug}.jpg, using preview.png (run npm run og)`);
      }

      const out = outputPathForRoute(route);
      await mkdir(path.dirname(out), { recursive: true });
      await writeFile(out, page, 'utf8');
      ok++;
      console.log(`  ✓  ${route}`);
    } catch (err) {
      failed++;
      console.warn(`  ⚠  ${route} — skipped (${err.message})`);
    }
  }

  // 6. Sitemap, RSS and LinkedIn feed
  await writeFile(path.join(distDir, 'sitemap.xml'), buildSitemap(resources), 'utf8');
  await writeFile(path.join(distDir, 'rss.xml'), buildRss(resources, images), 'utf8');
  await mkdir(path.join(distDir, 'feeds'), { recursive: true });
  await writeFile(path.join(distDir, 'feeds', 'linkedin.json'), await buildLinkedInFeed(resources, images), 'utf8');

  // 7. Clean up server bundle
  await rm(serverDistDir, { recursive: true, force: true });

  console.log(`\n✅  Prerender complete — ${ok} rendered, ${failed} skipped as SPA fallback.`);
}

run().catch((err) => {
  // Never fail the build — site still works as a React SPA without prerender.
  // ErrorBoundary + firstElementChild hydration fix keep the site visible.
  console.warn('\n⚠️  Prerender step failed entirely:', err.message);
  console.warn('Site deploys as a standard React SPA (Google still indexes it via JS rendering).');
});
